/**
 * Generates src/internal/phone-data.js, the phone field's compact country table, from
 * libphonenumber-js metadata (MIT; Google libphonenumber data, Apache-2.0):
 *   node scripts/build-phone-data.mjs
 * Each record: code, dial code, shortest and longest national length, trunk prefix, an example
 * mobile number, its digit groups, and whether it is the main country for its dial code.
 */
import { writeFileSync } from 'node:fs';
import { Metadata, getCountries, getCountryCallingCode, getExampleNumber } from 'libphonenumber-js/core';
import meta from 'libphonenumber-js/metadata.max.json';
import examples from 'libphonenumber-js/examples.mobile.json';

const metadata = new Metadata(meta);

/** Digit-run lengths of the national format, without the trunk prefix it starts with. */
function groups(formatted, national) {
  const runs = formatted.match(/\d+/g) ?? [];
  let extra = runs.join('').length - national.length;

  while (extra > 0 && runs.length) {
    const cut = Math.min(extra, runs[0].length);
    runs[0] = runs[0].slice(cut);

    if (!runs[0]) runs.shift();
    extra -= cut;
  }

  return runs.map((r) => r.length).join('.');
}

const records = getCountries(meta)
  .map((code) => {
    metadata.selectNumberingPlan(code);
    const dial = getCountryCallingCode(code, meta);
    const lengths = metadata.numberingPlan.possibleLengths() ?? [];
    const example = getExampleNumber(code, examples, meta);
    const national = example?.nationalNumber ?? '';
    const main = meta.country_calling_codes[dial][0] === code ? '1' : '';
    // The metadata stores "none" as the number 0 and a real trunk prefix as a string.
    const trunk = metadata.numberingPlan.nationalPrefix() || '';
    const digitGroups = example ? groups(example.formatNational(), national) : '';

    return [code, dial, Math.min(...lengths), Math.max(...lengths), trunk, national, digitGroups, main].join(',');
  })
  .toSorted();

const source = `// Generated by scripts/build-phone-data.mjs from libphonenumber-js metadata. Do not edit.
// libphonenumber-js: MIT License, Copyright (c) 2016 @catamphetamine. Its metadata is derived from
// Google's libphonenumber (Apache License 2.0, Copyright (C) The Libphonenumber Authors). Full texts:
// LICENSE-libphonenumber.txt in this package.
// code,dial,min,max,trunk,example,groups,main;…
export const DATA = ${JSON.stringify(records.join(';'))};
`;

writeFileSync(new URL('../src/internal/phone-data.js', import.meta.url), source);

console.log(`✓ phone-data.js: ${records.length} countries`);
