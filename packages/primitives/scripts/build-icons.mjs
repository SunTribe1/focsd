const n = (v) => String(Number(v));

/** A leading relative moveto becomes absolute (its implicit pairs stay relative), so paths can be joined. */
function absoluteStart(d) {
  const m = /^\s*m\s*(-?\d*\.?\d+)[\s,]*(-?\d*\.?\d+)\s*(.*)$/s.exec(d);

  if (!m) return d.trim();
  const [, x, y, rest] = m;

  if (!rest) return `M${x} ${y}`;

  return /^[-\d.]/.test(rest) ? `M${x} ${y}l${rest}` : `M${x} ${y}${rest}`;
}

/**
 * A polyline's or polygon's `points` as path data.
 * @param {string} points
 * @param {boolean} closed
 */
function pointsPath(points, closed) {
  // Lucide writes points as numbers separated by spaces and/or commas: pair them up.
  const numbers = String(points)
    .trim()
    .split(/[\s,]+/)
    .map(n);

  const pairs = numbers.flatMap((value, i) => (i % 2 ? [] : [`${value} ${numbers[i + 1]}`]));

  return `M${pairs.join('L')}${closed ? 'z' : ''}`;
}

/** One Lucide element (`[tag, attrs]`) as path data. */
export function nodeToPath([tag, a]) {
  switch (tag) {
    case 'path':
      return absoluteStart(a.d);
    case 'line':
      return `M${n(a.x1)} ${n(a.y1)}L${n(a.x2)} ${n(a.y2)}`;
    case 'circle': {
      const r = Number(a.r);

      return `M${n(a.cx - r)} ${n(a.cy)}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0-${2 * r} 0`;
    }

    case 'rect': {
      const [x, y, w, h] = [a.x ?? 0, a.y ?? 0, a.width, a.height].map(Number);
      const rx = Number(a.rx ?? a.ry ?? 0);
      const ry = Number(a.ry ?? a.rx ?? 0);

      if (!rx) return `M${x} ${y}h${w}v${h}h-${w}z`;

      return (
        `M${x + rx} ${y}h${w - 2 * rx}a${rx} ${ry} 0 0 1 ${rx} ${ry}v${h - 2 * ry}a${rx} ${ry} 0 0 1-${rx} ${ry}` +
        `h-${w - 2 * rx}a${rx} ${ry} 0 0 1-${rx}-${ry}v-${h - 2 * ry}a${rx} ${ry} 0 0 1 ${rx}-${ry}z`
      );
    }

    case 'polyline':
    case 'polygon':
      return pointsPath(a.points, tag === 'polygon');

    default:
      throw new Error(`build-icons: unsupported Lucide element <${tag}>`);
  }
}

/** Every system icon as one path `d` string, from the installed `lucide` package. */
export async function generateLucidePaths() {
  const lucide = await import('lucide');

  return Object.fromEntries(
    Object.entries(LUCIDE_NAMES).map(([name, lucideName]) => {
      let node = lucide[lucideName];

      if (!node) throw new Error(`build-icons: Lucide has no icon "${lucideName}"`);

      if (node[0] === 'svg') node = node[2];

      return [name, node.map(nodeToPath).join('')];
    }),
  );
}

const here = dirname(fileURLToPath(import.meta.url));

/** The file's source, with Lucide's license notice. */
export async function lucidePathsSource() {
  const require = createRequire(import.meta.url);
  const pkgPath = require.resolve('lucide/package.json');
  const { version } = JSON.parse(readFileSync(pkgPath, 'utf8'));
  const license = readFileSync(join(dirname(pkgPath), 'LICENSE'), 'utf8').trim();
  const paths = await generateLucidePaths();

  const body = Object.entries(paths)
    .map(([name, d]) => `  ${JSON.stringify(name)}: ${JSON.stringify(d)},`)
    .join('\n');

  return `// Generated by scripts/build-icons.mjs from lucide@${version}. Do not edit.
/*
${license}
*/

/** The default icon set: Lucide icons (24×24, 2px stroke, round caps), by system icon name. */
export const lucidePaths = {
${body}
};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(here, '../src/internal/lucide-paths.js'), await lucidePathsSource());
  console.log('✓ wrote src/internal/lucide-paths.js');
}
