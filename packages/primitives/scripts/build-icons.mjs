/**
 * Generates src/internal/lucide-paths.js: the default icon set, drawn from Lucide (ISC). Each icon
 * becomes one path `d` string under our system icon name, so the default library has no runtime
 * dependency and stays tree-shakable. Run after upgrading `lucide`:
 *   node scripts/build-icons.mjs
 */
