import { readFile, writeFile } from 'node:fs/promises';

const source = new URL('../node_modules/@focsd-dev/tokens/dist/floor.css', import.meta.url);
const target = new URL('../src/floor.styles.js', import.meta.url);
const css = await readFile(source, 'utf8');

await writeFile(
  target,
  `// Generated by scripts/sync-floor.mjs from @focsd-dev/tokens/dist/floor.css. Do not edit.
import { unsafeCSS } from 'lit';

export const floorCssText = ${JSON.stringify(css)};

/** The accessibility floor every Focsd element adopts: focus ring, 24px targets, forced colors, reduced motion. */
export const floorStyles = unsafeCSS(floorCssText);
`,
);

console.log('✓ wrote src/floor.styles.js');
