import { loadTokens } from './load.mjs';
import { atRule, declarations, rule } from './emit.mjs';
import { cssName } from './names.mjs';
import { colorToHexFallback, toCss } from './serialize.mjs';
import { REF, PRESETS, fullSet, presetFile, presetSet } from './passes.mjs';
import { colorMap } from './checks/contrast.mjs';
import { PRESET_DATA } from '../scripts/preset-palettes.mjs';

/** R6: every preset file declares the layer order, so a theme-builder override beats a preset. */
export const ORDER = '@layer focsd.tokens, focsd.preset, focsd.brand;';
const HEADER = '/* @focsd-dev/tokens: generated by build.mjs, do not edit */';
const SWATCH_KEYS = ['action', 'on-action', 'route', 'ground', 'surface'];

/** The four token passes of one preset: its ref palette, base (fonts, radii) and light/dark color roles. */
export async function loadPresetPasses(name) {
  const ref = await loadTokens({ source: [presetFile(name, 'ref')] });
  const base = await loadTokens({ source: [presetFile(name, 'base')] });
  const theme = (t) => loadTokens({ include: [...REF, presetFile(name, 'ref')], source: [presetFile(name, t)] });

  return { ref, base, light: await theme('light'), dark: await theme('dark') };
}

const reverted = (tokens) => tokens.map((t) => `${cssName(t.path)}: revert-layer;`);

const hexFallback = (selector, ref) =>
  atRule(
    '@supports not (color: oklch(0 0 0))',
    rule(
      selector,
      ref.map((t) => `${cssName(t.path)}: ${colorToHexFallback(t.value)};`),
    ),
  );

/**
 * A preset's extras: values that are not color roles (a gradient fill, chart series pointing at
 * category colors), written as-is after its roles. `theme` is `light` or `dark`.
 * @param {string} name
 * @param {'light' | 'dark'} theme
 */
const extras = (name, theme) => Object.entries(PRESET_DATA[name]?.extras?.[theme] ?? {}).map(([k, v]) => `--focsd-${k}: ${v};`);

/** The extras' names, reverted under the high-contrast theme like the color roles. */
const revertedExtras = (name) => Object.keys(PRESET_DATA[name]?.extras?.light ?? {}).map((k) => `--focsd-${k}: revert-layer;`);

/** The rules for one preset, inside @layer focsd.preset (R5, R8). */
function presetRules(name, { ref, base, light, dark }) {
  const b = `[data-focsd-brand="${name}"]`;
  const self = `${b}:not([data-focsd-theme])`;
  const lightRules = [...declarations(light), ...extras(name, 'light')];
  const darkRules = [...declarations(dark), ...extras(name, 'dark')];
  const contrast = [...reverted(light), ...revertedExtras(name)];

  return [
    rule(b, [...declarations(ref), ...declarations(base)]),
    hexFallback(b, ref),
    rule(`${b},\n${b} [data-focsd-theme="light"]`, lightRules),
    rule(`${b}[data-focsd-theme="dark"],\n${b} [data-focsd-theme="dark"]`, darkRules),
    atRule('@media (prefers-color-scheme: dark)', rule(self, darkRules)),
    // A preset on an element inside a themed page or section follows that theme, not the system
    // setting (otherwise a light page shows a dark-system preset as dark text on a dark surface).
    rule(`[data-focsd-theme="light"] ${self}`, lightRules),
    rule(`[data-focsd-theme="dark"] ${self}`, darkRules),
    rule(`${b}[data-focsd-theme="contrast"],\n${b} [data-focsd-theme="contrast"],\n[data-focsd-theme="contrast"] ${b}`, contrast),
    atRule('@media (prefers-contrast: more)', rule(self, contrast)),
  ].join('\n\n');
}

const file = (body) => `${ORDER}\n${HEADER}\n${atRule('@layer focsd.preset', body)}\n`;

/** dist/presets/<name>.css */
export const assemblePreset = (name, passes) => file(presetRules(name, passes));

/** dist/presets.css: all presets after one order statement. */
export const assemblePresets = (all) => file(PRESETS.map((name) => presetRules(name, all[name])).join('\n\n'));

const swatches = async (set) => {
  const out = {};

  for (const theme of ['light', 'dark']) {
    const colors = colorMap(await loadTokens(set(theme)));
    out[theme] = Object.fromEntries(SWATCH_KEYS.map((k) => [k, colorToHexFallback(colors.get(k))]));
  }

  return out;
};

const fontStack = (tokens, key) => {
  const t = tokens.find((x) => x.path.join('.') === `sys.font.${key}`);

  return t ? toCss(t.value, t.type) : undefined;
};

/** dist/presets.json: label, fonts, radii and hex swatches per preset; the default (Wayfinding) swatches too. */
export async function presetsData() {
  const presets = {};

  for (const name of PRESETS) {
    const { base } = await loadPresetPasses(name);
    const radius = Object.fromEntries(base.filter((t) => t.path[1] === 'radius').map((t) => [t.path[2], toCss(t.value, t.type)]));
    const fonts = { sans: fontStack(base, 'sans'), mono: fontStack(base, 'mono') ?? null };

    presets[name] = {
      label: PRESET_DATA[name].label,
      mood: PRESET_DATA[name].mood,
      fonts,
      radius,
      swatches: await swatches((theme) => presetSet(name, theme)),
    };
  }

  return { default: { label: 'Wayfinding', swatches: await swatches((theme) => fullSet(theme, 'comfortable')) }, presets };
}
