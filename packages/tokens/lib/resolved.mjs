import { createHash } from 'node:crypto';
import { loadTokens } from './load.mjs';
import { DENSITIES, PRESETS, THEMES, fullSet } from './passes.mjs';
import { cssName } from './names.mjs';
import { colorToHexFallback, toCss } from './serialize.mjs';

export async function resolveAll() {
  const rows = [];

  for (const theme of THEMES) {
    for (const density of DENSITIES) {
      for (const t of await loadTokens(fullSet(theme, density))) {
        if (t.path[0] !== 'sys') continue;
        const css = cssName(t.path);
        const row = { theme, density, name: css.slice('--focsd-'.length), css, value: toCss(t.value, t.type) };

        if (t.type === 'color') row.hex = colorToHexFallback(t.value);
        rows.push(row);
      }
    }
  }

  return rows;
}

export const systemNames = (rows) => [...new Set(rows.map((r) => r.name))].toSorted();

const quoted = (list, sep = ' | ') => list.map((n) => `'${n}'`).join(sep);

/**
 * Inline <head> snippet (R9, ≤ 400 bytes): applies the stored theme and brand to <html> before first paint.
 * Only known values are applied; storage errors (private mode, blocked) are swallowed.
 */
export const NO_FLASH_SCRIPT = `(function(){try{var d=document.documentElement,s=localStorage,t=s.getItem("focsd-theme"),b=s.getItem("focsd-brand");/^(${THEMES.join('|')})$/.test(t)&&d.setAttribute("data-focsd-theme",t);/^(${PRESETS.join('|')})$/.test(b)&&d.setAttribute("data-focsd-brand",b)}catch(e){}})()`;

/** CSP `script-src` source for the snippet. */
export const noFlashHash = (script) => `sha256-${createHash('sha256').update(script).digest('base64')}`;

const frozenSwatches = (byTheme) =>
  `Object.freeze({ ${Object.entries(byTheme)
    .map(([theme, sw]) => `${theme}: Object.freeze(${JSON.stringify(sw)})`)
    .join(', ')} })`;

const presetJs = (data) => `export const brands = Object.freeze(${JSON.stringify(PRESETS)});
export function setBrand(brand, root = globalThis.document?.documentElement) {
  if (brand !== null && !brands.includes(brand)) throw new Error(\`Unknown Focsd brand "\${brand}"\`);
  if (!root) throw new Error('setBrand: no document here (server rendering); pass the root element');
  if (brand === null) root.removeAttribute('data-focsd-brand');
  else root.setAttribute('data-focsd-brand', brand);
}
export function clearTheme(root = globalThis.document?.documentElement) {
  if (!root) throw new Error('clearTheme: no document here (server rendering); pass the root element');
  root.removeAttribute('data-focsd-theme');
}
export const presetSwatches = Object.freeze({
${PRESETS.map((name) => `  ${name}: ${frozenSwatches(data.presets[name].swatches)},`).join('\n')}
});
export const defaultSwatches = ${frozenSwatches(data.default.swatches)};
export const noFlashScript = ${JSON.stringify(NO_FLASH_SCRIPT)};
export const noFlashHash = ${JSON.stringify(noFlashHash(NO_FLASH_SCRIPT))};
`;

export const jsSource = (names, presets) => `// @focsd-dev/tokens: generated by build.mjs, do not edit
export const tokenNames = Object.freeze(${JSON.stringify(names)});
const known = new Set(tokenNames);
export function cssVar(name) {
  if (!known.has(name)) throw new Error(\`Unknown Focsd token "\${name}"\`);
  return \`var(--focsd-\${name})\`;
}
export const themes = Object.freeze(${JSON.stringify(THEMES)});
export const densities = Object.freeze(${JSON.stringify(DENSITIES)});
function setMode(kind, list, value, root) {
  if (!list.includes(value)) throw new Error(\`Unknown Focsd \${kind} "\${value}"\`);
  if (!root) throw new Error(\`set\${kind[0].toUpperCase()}\${kind.slice(1)}: no document here (server rendering); pass the root element\`);
  root.setAttribute(\`data-focsd-\${kind}\`, value);
}
export function setTheme(theme, root = globalThis.document?.documentElement) {
  setMode('theme', themes, theme, root);
}
export function setDensity(density, root = globalThis.document?.documentElement) {
  setMode('density', densities, density, root);
}
${presetJs(presets)}`;

