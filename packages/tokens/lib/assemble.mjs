import { loadTokens } from './load.mjs';
import { atRule, declarations, rule } from './emit.mjs';
import { cssName } from './names.mjs';
import { colorToHexFallback } from './serialize.mjs';
import { BASE, DENSITIES, REF, THEMES, densityFile, themeFile } from './passes.mjs';

const HEADER = '/* @focsd-dev/tokens: generated by build.mjs, do not edit */';
const SCHEME = { light: 'light', dark: 'dark', contrast: 'light' };

export async function loadPasses() {
  const base = await loadTokens({ source: [...REF, BASE, themeFile('light'), densityFile('default')] });
  const themes = {};

  for (const theme of THEMES) themes[theme] = await loadTokens({ include: REF, source: [themeFile(theme)] });
  const densities = {};

  for (const density of DENSITIES) densities[density] = await loadTokens({ include: REF, source: [densityFile(density)] });

  return { base, themes, densities };
}

const themeRule = (selector, theme, tokens) => rule(selector, [`color-scheme: ${SCHEME[theme]};`, ...declarations(tokens)]);

const hexFallback = (base) =>
  atRule(
    '@supports not (color: oklch(0 0 0))',
    rule(
      ':root',
      base.filter((t) => t.path[0] === 'ref' && t.type === 'color').map((t) => `${cssName(t.path)}: ${colorToHexFallback(t.value)};`),
    ),
  );

const REDUCED_MOTION = atRule(
  '@media (prefers-reduced-motion: reduce)',
  rule(':root', ['--focsd-duration-quick: 0ms;', '--focsd-duration-base: 0ms;', '--focsd-duration-slow: 0ms;']),
);

const wrap = (blocks) => `${HEADER}\n${atRule('@layer focsd.tokens', blocks.join('\n\n'))}\n`;

/** dist/tokens.css: all themes and densities, switched by attribute or user preference. */
/** Densities switch by attribute on any subtree; `default` restores the standard size inside another. */
const densityRules = ({ densities }) => DENSITIES.map((d) => rule(`[data-focsd-density="${d}"]`, declarations(densities[d])));

export function assembleAll({ base, themes, densities }) {
  return wrap([
    themeRule(':root', 'light', base),
    hexFallback(base),
    atRule('@media (prefers-color-scheme: dark)', themeRule(':root:not([data-focsd-theme])', 'dark', themes.dark)),
    atRule('@media (prefers-contrast: more)', themeRule(':root:not([data-focsd-theme])', 'contrast', themes.contrast)),
    ...THEMES.map((theme) => themeRule(`[data-focsd-theme="${theme}"]`, theme, themes[theme])),
    ...densityRules({ densities }),
    REDUCED_MOTION,
  ]);
}

/** dist/themes/<theme>.css: one fixed theme on :root, densities and reduced motion still available. */
export function assembleTheme(theme, { base, themes, densities }) {
  return wrap([
    rule(':root', declarations(base)),
    hexFallback(base),
    themeRule(':root', theme, themes[theme]),
    ...densityRules({ densities }),
    REDUCED_MOTION,
  ]);
}
