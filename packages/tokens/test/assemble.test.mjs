import { gzipSync } from 'node:zlib';
import { beforeAll, describe, expect, it } from 'vitest';
import { assembleAll, assembleTheme, loadPasses } from '../lib/assemble.mjs';
import { cssName } from '../lib/names.mjs';
import { colorToHexFallback } from '../lib/serialize.mjs';

let passes;
let css;

beforeAll(async () => {
  passes = await loadPasses();
  css = assembleAll(passes);
});

describe('tokens.css', () => {
  it('is one generated, cascade-layered stylesheet', () => {
    expect(css.startsWith('/* @focsd/tokens: generated by build.mjs, do not edit */\n@layer focsd.tokens {')).toBe(true);
    expect(css).not.toContain('@font-face');
  });

  it('declares light defaults on :root with aliases kept as var()', () => {
    expect(css).toContain('  :root {\n    color-scheme: light;');
    expect(css).toContain('--focsd-ink: var(--focsd-ref-graphite-21);');
    expect(css).toContain('--focsd-ref-graphite-21: oklch(');
  });

  it('switches by attribute and by user preference, contrast after dark', () => {
    for (const t of ['light', 'dark', 'contrast']) expect(css).toContain(`[data-focsd-theme="${t}"] {`);
    const dark = css.indexOf('@media (prefers-color-scheme: dark)');
    const more = css.indexOf('@media (prefers-contrast: more)');
    expect(dark).toBeGreaterThan(-1);
    expect(more).toBeGreaterThan(dark);
    expect(css).toContain(':root:not([data-focsd-theme]) {');
    expect(css).toContain('[data-focsd-density="compact"] {');
    expect(css).toContain('@media (prefers-reduced-motion: reduce)');
  });

  it('has a hex fallback for every reference color (Review Focus 2)', () => {
    const start = css.indexOf('@supports not (color: oklch(0 0 0))');
    expect(start).toBeGreaterThan(-1);
    const block = css.slice(start, css.indexOf('\n  }\n', css.indexOf(':root', start)));
    const refColors = passes.base.filter((t) => t.path[0] === 'ref' && t.type === 'color');
    expect(refColors.length).toBe(54);

    for (const t of refColors) expect(block).toContain(`${cssName(t.path)}: ${colorToHexFallback(t.value)};`);
  });

  it('only reference declarations contain literal oklch() (everything else falls back via var)', () => {
    const offenders = css.split('\n').filter((l) => l.includes('oklch(') && !/^\s*--focsd-ref-/.test(l) && !l.includes('@supports'));
    expect(offenders).toEqual([]);
  });

  it('defaults to 36px controls and can switch density on any subtree', () => {
    const root = css.indexOf(':root {');
    expect(css.slice(root, css.indexOf('}', root))).toContain('--focsd-control-height: 36px;');

    for (const [density, height] of [
      ['default', '36px'],
      ['comfortable', '44px'],
      ['compact', '32px'],
    ]) {
      const at = css.indexOf(`[data-focsd-density="${density}"] {`);
      expect(at, density).toBeGreaterThan(-1);
      expect(css.slice(at, css.indexOf('}', at))).toContain(`--focsd-control-height: ${height};`);
    }
  });

  it('stays within the 4 KB gzip budget', () => {
    expect(gzipSync(css).length).toBeLessThanOrEqual(4096);
  });

  it('matches the reviewed snapshot', () => {
    expect(css).toMatchSnapshot();
  });
});

describe('themes/<theme>.css', () => {
  it('puts the chosen theme on :root and has no attribute switching', () => {
    const dark = assembleTheme('dark', passes);
    expect(dark).toContain('color-scheme: dark;');
    expect(dark).toContain('--focsd-ground: var(--focsd-ref-neutral-18);');
    expect(dark).not.toContain('[data-focsd-theme=');
  });
});
