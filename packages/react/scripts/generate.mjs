/**
 * Generates src/index.js and src/index.d.ts plus src/elements/<name>.js per element: a React
 * wrapper (via @lit/react) for every Focsd element, from each package's custom elements manifest.
 * A component wrapper (`@focsd-dev/react/date-picker`) loads only the module that defines it. The data
 * grid, chart and rich-text editor wrappers (`@focsd-dev/react/data-grid`, `/chart`, `/rich-text`) load
 * their own package, an optional peer dependency, so they are subpath-only: the main entry stays
 * installable without them. Element events become React props: `change` → onChange,
 * `focsd-select` → onFocsdSelect, typed `EventName<CustomEvent<Detail>>` when the event has a
 * detail. Run after building the element packages:
 *   node scripts/generate.mjs
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';

/**
 * Element packages. `entry` maps the declaring module to the import path; `barrel` is whether the
 * main entry re-exports the package's wrappers.
 * @type {{ pkg: string, dir: string, entry: (module: string) => string, barrel: boolean }[]}
 */
const PACKAGES = [
  { pkg: '@focsd-dev/components', dir: 'components', entry: (module) => `@focsd-dev/components/${module}`, barrel: true },
  { pkg: '@focsd-dev/data-grid', dir: 'data-grid', entry: () => '@focsd-dev/data-grid', barrel: false },
  { pkg: '@focsd-dev/charts', dir: 'charts', entry: () => '@focsd-dev/charts', barrel: false },
  { pkg: '@focsd-dev/ai', dir: 'ai', entry: () => '@focsd-dev/ai', barrel: false },
  { pkg: '@focsd-dev/editor', dir: 'editor', entry: () => '@focsd-dev/editor', barrel: false },
];

/** Private signals between elements: never a React prop. */
const INTERNAL_EVENTS = new Set(['focsd-tree-item-change']);
const DOM = new Set(['click', 'input', 'focus', 'blur', 'keydown', 'keyup']);
const DETAIL = /^CustomEvent<([A-Za-z]\w*)>$/;

const prop = (event) => `on${event.replaceAll(/(^|[-:])([a-z])/g, (_, __, c) => c.toUpperCase())}`;

/** @param {string} dir */
const readManifest = (dir) => JSON.parse(readFileSync(new URL(`../../${dir}/custom-elements.json`, import.meta.url), 'utf8'));

/**
 * The element's events as `{ name, detail }`, sorted; a named control also fires input and change.
 * @param {any} d
 */
function eventsOf(d) {
  /** @type {Map<string, string | undefined>} */
  const events = new Map();

  for (const e of d.events ?? []) {
    if (e.name && !INTERNAL_EVENTS.has(e.name)) events.set(e.name, DETAIL.exec(e.type?.text ?? '')?.[1]);
  }

  if (d.attributes?.some((a) => a.name === 'name')) {
    for (const name of ['input', 'change']) if (!events.has(name)) events.set(name, undefined);
  }

  return [...events]
    .flatMap(([name, detail]) => (DOM.has(name) && name !== 'input' ? [] : [{ name, detail }]))
    .toSorted((a, b) => a.name.localeCompare(b.name));
}

const rows = PACKAGES.flatMap(({ pkg, dir, entry, barrel }) =>
  readManifest(dir)
    .modules.flatMap((m) => (m.declarations ?? []).map((d) => ({ ...d, module: m.path.split('/').pop() })))
    .filter((d) => d.tagName && d.name)
    .map((d) => ({
      pkg,
      barrel,
      tag: d.tagName,
      slug: d.tagName.replace(/^focsd-/, ''),
      className: d.name,
      name: d.name.replace(/^Focsd/, ''),
      from: entry(d.module),
      events: eventsOf(d),
    })),
).toSorted((a, b) => a.name.localeCompare(b.name));

const banner = '// Generated by scripts/generate.mjs from the Focsd custom-elements.json manifests. Do not edit.\n';

/** One entry per element, importing only the module that defines it. */
const elementJs = (r) => `${banner}import * as React from 'react';
import { createComponent } from '@lit/react';
import { ${r.className} } from '${r.from}';

export const ${r.name} = createComponent({
  react: React,
  tagName: '${r.tag}',
  elementClass: ${r.className},
  displayName: '${r.name}',
  events: { ${r.events.map((e) => `${prop(e.name)}: '${e.name}'`).join(', ')} },
});
`;

const eventType = (r, e) => (e.detail ? `EventName<CustomEvent<import('${r.pkg}').${e.detail}>>` : 'EventName<Event>');

const elementDts = (r) => `${banner}import type { EventName, ReactWebComponent } from '@lit/react';
import type { ${r.className} } from '${r.from}';

export declare const ${r.name}: ReactWebComponent<${r.className}, { ${r.events.map((e) => `${prop(e.name)}: ${eventType(r, e)}`).join('; ')} }>;
`;

const barrel = `${banner}${rows.flatMap((r) => (r.barrel ? [`export { ${r.name} } from './elements/${r.slug}.js';`] : [])).join('\n')}\n`;

const files = [
  [new URL('../src/index.js', import.meta.url), barrel],
  [new URL('../src/index.d.ts', import.meta.url), barrel],
  ...rows.flatMap((r) => [
    [new URL(`../src/elements/${r.slug}.js`, import.meta.url), elementJs(r)],
    [new URL(`../src/elements/${r.slug}.d.ts`, import.meta.url), elementDts(r)],
  ]),
];

const current = (url) => (existsSync(url) ? readFileSync(url, 'utf8') : null);

if (process.argv.includes('--check')) {
  const stale = files.filter(([url, text]) => current(url) !== text);

  if (stale.length) {
    console.error('@focsd-dev/react wrappers are out of date with the element manifests: run `pnpm --filter @focsd-dev/react generate`.');
    process.exit(1);
  }

  console.log(`✓ @focsd-dev/react: ${rows.length} wrappers up to date`);
} else {
  mkdirSync(new URL('../src/elements/', import.meta.url), { recursive: true });

  for (const [url, text] of files) writeFileSync(url, text);
  console.log(`✓ @focsd-dev/react: ${rows.length} wrappers`);
}
