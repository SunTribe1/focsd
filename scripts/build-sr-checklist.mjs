/**
 * Writes docs/a11y/screen-reader-checklist.md, the manual screen-reader pass for every component,
 * from the same data the docs pages use (catalogue + each component's accessibility notes and
 * keyboard table), so the checklist cannot fall behind the components.
 *
 *   node scripts/build-sr-checklist.mjs           write the file
 *   node scripts/build-sr-checklist.mjs --check   fail when the file is out of date
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import process from 'node:process';
import { components, CATEGORIES } from '../apps/docs/src/data/catalogue.js';
import { examples } from '../apps/docs/src/data/examples/index.js';

const target = new URL('../docs/a11y/screen-reader-checklist.md', import.meta.url);

const intro = `<!-- Generated by scripts/build-sr-checklist.mjs from the docs data. Do not edit; change the
     component's accessibility notes or keyboard table in apps/docs/src/data/examples instead. -->

# Screen-reader checklist

A manual pass for every component, run before each release. Automated tests already check roles,
names and states (Playwright ARIA snapshots), keyboard scripts, live-region announcements and
axe-core WCAG 2.2 AA in Chromium, Firefox and WebKit. What they cannot check is how a real screen
reader speaks and navigates, so a person does this pass.

**Setup.** Run the docs (\`pnpm docs\`) and open each component's page; its live examples are the
test surface. Use at least one desktop and one mobile pairing per release, rotating the rest:

| Screen reader | Browser | Platform |
|---|---|---|
| NVDA | Firefox or Chrome | Windows |
| JAWS | Chrome | Windows |
| VoiceOver | Safari | macOS |
| VoiceOver | Safari | iOS |
| TalkBack | Chrome | Android |

**For every component:**
- Tab to it and listen: its role, name, value and state are spoken, and nothing is read twice.
- Use the browse or virtual cursor (NVDA browse mode, VoiceOver VO+arrows) as well as Tab.
- Press each key in its keyboard table and listen for the change to be announced.
- Check each accessibility note below by ear.

**Record** pass or fail per row, with the screen reader, browser and what was spoken. File failures
against the component with that transcript.

**Every page:**
- [ ] Headings and landmarks are listed correctly in the screen reader's rotor or elements list.
- [ ] 200% zoom and 200% text-only zoom: nothing is clipped or overlapping.
- [ ] Windows High Contrast (forced colors): focus and borders stay visible.
- [ ] Reduced motion: nothing animates.
- [ ] Safari: the two-tone focus ring is visible (Playwright's WebKit cannot verify it).
`;

/** @param {string} text */
const plain = (text) => text.replaceAll('\n', ' ').trim();

/** @param {(typeof components)[number]} component */
function section(component) {
  const example = examples[component.slug];
  const lines = [`### ${component.name} (\`<${component.tag}>\`)`, '', `Pattern: ${component.pattern}.`, ''];

  for (const note of example?.a11y ?? []) lines.push(`- [ ] ${plain(note)}`);

  for (const [keys, effect] of example?.keyboard ?? []) lines.push(`- [ ] **${plain(keys)}:** ${plain(effect)}`);

  for (const more of example?.more ?? []) {
    lines.push('', `${more.title}:`, '');

    for (const note of more.a11y) lines.push(`- [ ] ${plain(note)}`);

    for (const [keys, effect] of more.keyboard ?? []) lines.push(`- [ ] **${plain(keys)}:** ${plain(effect)}`);
  }

  if (!example) lines.push('- [ ] No accessibility notes yet: test with the general checks above.');

  return lines.join('\n');
}

const body = CATEGORIES.flatMap((category) => {
  const inCategory = components.filter((c) => c.category === category);

  return inCategory.length ? [`## ${category}`, ...inCategory.map(section)] : [];
});

const output = `${[intro, ...body].join('\n\n')}\n`;

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';

  if (current !== output) {
    console.error('docs/a11y/screen-reader-checklist.md is out of date: run node scripts/build-sr-checklist.mjs');
    process.exitCode = 1;
  }
} else {
  writeFileSync(target, output);
  console.log(`✓ screen-reader-checklist.md: ${components.length} components`);
}
